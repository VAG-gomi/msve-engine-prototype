"""Machine-readable error codes for the MSVE prototype pipeline."""

ADMISSION_REJECTED = "ADMISSION_REJECTED"
CAPACITY_EXCEEDED = "CAPACITY_EXCEEDED"
UNSUPPORTED_KIND = "UNSUPPORTED_KIND"
UNSUPPORTED_BASIS = "UNSUPPORTED_BASIS"
UNDERSPECIFIED = "UNDERSPECIFIED"
MALFORMED_INPUT = "MALFORMED_INPUT"
UNKNOWN_SPEC_VERSION = "UNKNOWN_SPEC_VERSION"
QUERY_DENOTATION_FAILED = "QUERY_DENOTATION_FAILED"
SOLVER_EXECUTION_FAILED = "SOLVER_EXECUTION_FAILED"
CHECKER_DISAGREEMENT = "CHECKER_DISAGREEMENT"
EVIDENCE_MISSING = "EVIDENCE_MISSING"


class MSVEError(Exception):
    def __init__(self, code, message, details=None):
        super().__init__(message)
        self.code = code
        self.details = details or {}
